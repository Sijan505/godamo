// ─── Request bodies ─────────────────────────────────────────────────────────

const MAX_QTY = 99_999_999_999.999;

/** A line to sell. There is deliberately no price field: the server prices it. */
export const SaleItemDto = schema({
  productId: [isUuid()],
  unitId: [isUuid()],
  /** In the chosen unit */
  quantity: [isNumber({ maxDecimalPlaces: 3 }), isPositive(), max(MAX_QTY)],
  /** Line discount in %. Salesmen: at most 5. */
  discountPercent: [optional(), isNumber({ maxDecimalPlaces: 2 }), min(0), max(100)],
});

const CreateSalesOrderDto = schema({
  partyId: [isUuid()],
  godownId: [isUuid()],
  items: [isArray(), arrayMinSize(1), arrayMaxSize(200), nested(SaleItemDto)],
  notes: [optional(), trim(), isString(), length(1, 1000)],
  /** Unique id generated by the (offline) client. Sending the same id again returns the existing order. */
  clientUuid: [optional(), isUuid()],
  /** Office staff booking for a salesman. Ignored for salesmen (always themselves). */
  salesmanId: [optional(), isUuid()],
});

const UpdateSalesOrderDto = schema({
  godownId: [optional(), isUuid()],
  /** Replaces all items */
  items: [optional(), isArray(), arrayMinSize(1), arrayMaxSize(200), nested(SaleItemDto)],
  notes: [optional(), trim(), isString(), length(1, 1000)],
});

export const CancelDto = schema({
  reason: [trim(), isString(), length(3, 500)],
});

const ListSalesOrdersQueryDto = schema(
  {
    status: [optional(), isEnum(OrderStatus)],
    partyId: [optional(), isUuid()],
    /** Ignored for salesmen (always themselves) */
    salesmanId: [optional(), isUuid()],
    from: [optional(), dateOnly()],
    to: [optional(), dateOnly()],
    ...paginationFields,
  },
  { defaults: paginationDefaults },
);

// ─── Service ────────────────────────────────────────────────────────────────

const DETAIL_INCLUDE = {
  party: { select: { id: true, name: true, phone: true } },
  salesman: { select: { id: true, name: true } },
  godown: { select: { id: true, name: true } },
  items: {
    include: {
      product: { select: { id: true, sku: true, name: true } },
      unit: { select: { id: true, name: true } },
    },
  },
  invoices: { select: { id: true, fiscalYear: true, invoiceNo: true, status: true } },
};

/** Salesmen only ever see their own orders; everyone else sees all. */
function scope(actor) {
  return {
    tenantId: actor.tenantId,
    ...(actor.role === UserRole.SALESMAN && { salesmanId: actor.userId }),
  };
}

export async function list(actor, q) {
  const where = {
    ...(q.salesmanId && { salesmanId: q.salesmanId }),
    ...scope(actor),
    status: q.status,
    partyId: q.partyId,
    ...((q.from || q.to) && {
      orderDate: {
        ...(q.from && { gte: toDateOnly(q.from) }),
        ...(q.to && { lte: toDateOnly(q.to) }),
      },
    }),
  };
  const [items, total] = await Promise.all([
    prisma.salesOrder.findMany({
      where,
      include: {
        party: { select: { id: true, name: true } },
        salesman: { select: { id: true, name: true } },
        godown: { select: { id: true, name: true } },
      },
      orderBy: [{ orderDate: 'desc' }, { createdAt: 'desc' }],
      ...pageArgs(q),
    }),
    prisma.salesOrder.count({ where }),
  ]);
  return { items, total, page: q.page, limit: q.limit };
}

export async function findOne(actor, id) {
  const order = await prisma.salesOrder.findFirst({
    where: { id, ...scope(actor) },
    include: DETAIL_INCLUDE,
  });
  if (!order) throw NotFound('Sales order not found');
  return order;
}

/**
 * Creates a DRAFT order priced by the server. With a clientUuid that was
 * already used, returns that order instead (safe to retry from the field app).
 */
export async function create(actor, dto) {
  if (dto.clientUuid) {
    const existing = await findByClientUuid(actor, dto.clientUuid);
    if (existing) return existing;
  }

  const party = await getCustomer(actor, dto.partyId);
  const godown = await getActiveGodown(actor, dto.godownId);
  const salesmanId = await resolveSalesman(actor, dto.salesmanId);
  const priced = await priceSale(actor, party.id, dto.items);
  const stockWarnings = await getStockWarnings(actor, godown.id, priced);

  try {
    const order = await prisma.$transaction(async (tx) => {
      const orderNo = await nextSalesOrderNo(tx, actor.tenantId, getFiscalYear(new Date()));
      const created = await tx.salesOrder.create({
        data: {
          tenantId: actor.tenantId,
          orderNo,
          partyId: party.id,
          salesmanId,
          godownId: godown.id,
          orderDate: nepalToday(),
          notes: dto.notes,
          clientUuid: dto.clientUuid,
          ...totalsData(priced),
          items: { create: itemsData(actor, priced) },
        },
      });
      await auditLog(
        {
          tenantId: actor.tenantId,
          userId: actor.userId,
          entity: 'SalesOrder',
          entityId: created.id,
          action: AuditAction.CREATE,
          newValue: { orderNo, partyId: party.id, total: priced.totals.total, items: dto.items },
        },
        tx,
      );
      return created;
    });
    return { ...(await findOne(actor, order.id)), stockWarnings };
  } catch (e) {
    // Two retries of the same offline order racing each other: one wins.
    if (dto.clientUuid && isUniqueViolation(e)) {
      const existing = await findByClientUuid(actor, dto.clientUuid);
      if (existing) return existing;
    }
    throw e;
  }
}

/** Edits a DRAFT order; items (if given) replace the old ones and are re-priced. */
export async function update(actor, id, dto) {
  const before = await findOne(actor, id);
  if (before.status !== OrderStatus.DRAFT) {
    throw Conflict(`Only DRAFT orders can be edited (this one is ${before.status})`);
  }
  const godownId = dto.godownId ? (await getActiveGodown(actor, dto.godownId)).id : before.godownId;
  const priced = dto.items ? await priceSale(actor, before.partyId, dto.items) : null;
  const stockWarnings = priced ? await getStockWarnings(actor, godownId, priced) : [];

  await prisma.$transaction(async (tx) => {
    const { count } = await tx.salesOrder.updateMany({
      where: { id, status: OrderStatus.DRAFT },
      data: { godownId, notes: dto.notes, ...(priced && totalsData(priced)) },
    });
    if (!count) throw Conflict('Only DRAFT orders can be edited');
    if (priced) {
      await tx.salesOrderItem.deleteMany({ where: { orderId: id } });
      await tx.salesOrderItem.createMany({
        data: itemsData(actor, priced).map((i) => ({ ...i, orderId: id })),
      });
    }
    await auditLog(
      {
        tenantId: actor.tenantId,
        userId: actor.userId,
        entity: 'SalesOrder',
        entityId: id,
        action: AuditAction.UPDATE,
        oldValue: {
          godownId: before.godownId,
          notes: before.notes,
          total: before.total,
          items: before.items.map((i) => ({
            productId: i.productId,
            unitId: i.unitId,
            quantity: i.quantity,
            discountPercent: i.discountPercent,
          })),
        },
        newValue: { godownId, notes: dto.notes, total: priced?.totals.total, items: dto.items },
      },
      tx,
    );
  });
  return { ...(await findOne(actor, id)), stockWarnings };
}

export function confirm(actor, id) {
  return changeStatus(actor, id, [OrderStatus.DRAFT], OrderStatus.CONFIRMED);
}

export function cancel(actor, id, reason) {
  return changeStatus(actor, id, [OrderStatus.DRAFT, OrderStatus.CONFIRMED], OrderStatus.CANCELLED, reason);
}

async function changeStatus(actor, id, from, to, reason) {
  const order = await findOne(actor, id);
  if (!from.includes(order.status)) {
    throw Conflict(
      `Cannot change a ${order.status} order to ${to}` +
        (order.status === OrderStatus.BILLED ? ' (cancel its invoice instead)' : ''),
    );
  }
  await prisma.$transaction(async (tx) => {
    const { count } = await tx.salesOrder.updateMany({
      where: { id, status: { in: from } },
      data: { status: to, ...(reason && { cancelReason: reason }) },
    });
    if (!count) throw Conflict('The order changed meanwhile; reload it');
    await auditLog(
      {
        tenantId: actor.tenantId,
        userId: actor.userId,
        entity: 'SalesOrder',
        entityId: id,
        action: to === OrderStatus.CANCELLED ? AuditAction.CANCEL : AuditAction.UPDATE,
        oldValue: { status: order.status },
        newValue: { status: to, reason },
      },
      tx,
    );
  });
  return findOne(actor, id);
}

async function findByClientUuid(actor, clientUuid) {
  const existing = await prisma.salesOrder.findUnique({
    where: { clientUuid },
    include: DETAIL_INCLUDE,
  });
  if (!existing) return null;
  const visible =
    existing.tenantId === actor.tenantId &&
    (actor.role !== UserRole.SALESMAN || existing.salesmanId === actor.userId);
  if (!visible) throw Conflict('This clientUuid is already used by another order');
  return { ...existing, stockWarnings: [], idempotentReplay: true };
}

async function resolveSalesman(actor, salesmanId) {
  if (actor.role === UserRole.SALESMAN || !salesmanId) return actor.userId;
  const user = await prisma.user.findFirst({
    where: { id: salesmanId, tenantId: actor.tenantId, isActive: true },
  });
  if (!user || user.role !== UserRole.SALESMAN) {
    throw BadRequest('salesmanId must be an active salesman');
  }
  return user.id;
}

/** A warning (not a block) for every product the godown can't currently cover. */
async function getStockWarnings(actor, godownId, priced) {
  const wanted = new Map();
  for (const line of priced.lines) {
    const entry = wanted.get(line.product.id);
    wanted.set(line.product.id, {
      line,
      qty: (entry?.qty ?? new Decimal(0)).plus(line.baseQty),
    });
  }
  const warnings = [];
  for (const [productId, { line, qty }] of wanted) {
    const available = await getBalance(prisma, actor.tenantId, godownId, productId);
    if (available.lt(qty)) {
      const units = line.product.units;
      const req = fromBase(qty, units).text;
      const have = fromBase(Decimal.max(available, 0), units).text;
      warnings.push({
        productId,
        productName: line.product.name,
        requested: req,
        available: have,
        message: `Only ${have} of ${line.product.name} in stock (ordered ${req})`,
      });
    }
  }
  return warnings;
}

function totalsData(priced) {
  const t = priced.totals;
  return {
    subtotal: t.subtotal,
    discount: priced.lines.reduce((s, l) => s.plus(l.discount), new Decimal(0)),
    vatAmount: t.vatAmount,
    total: t.total,
  };
}

function itemsData(actor, priced) {
  return priced.lines.map((l, i) => ({
    tenantId: actor.tenantId,
    productId: l.product.id,
    unitId: l.unitId,
    quantity: l.quantity,
    baseQuantity: l.baseQty,
    rate: l.rate,
    discountPercent: l.discountPercent,
    discount: l.discount,
    vatAmount: priced.totals.lines[i].vatAmount,
    amount: priced.totals.lines[i].amount,
    priceSource: l.priceSource,
  }));
}

// ─── Routes ─────────────────────────────────────────────────────────────────

const r = controller('/sales-orders', {
  roles: [UserRole.OWNER, UserRole.MANAGER, UserRole.OFFICE, UserRole.SALESMAN],
});

// Salesmen see only their own orders.
r.get('/', { query: ListSalesOrdersQueryDto }, ({ user, query }) => list(user, query));
r.get('/:id', { params: { id: 'uuid' } }, ({ user, params }) => findOne(user, params.id));
// Prices come from the server; the same clientUuid returns the existing order.
r.post('/', { body: CreateSalesOrderDto }, ({ user, body }) => create(user, body));
// Edit a DRAFT order (items are re-priced)
r.patch('/:id', { params: { id: 'uuid' }, body: UpdateSalesOrderDto }, ({ user, params, body }) =>
  update(user, params.id, body),
);
r.post('/:id/confirm', { status: 200, params: { id: 'uuid' } }, ({ user, params }) => confirm(user, params.id));
r.post('/:id/cancel', { status: 200, params: { id: 'uuid' }, body: CancelDto }, ({ user, params, body }) =>
  cancel(user, params.id, body.reason),
);

export const salesOrdersRoutes = r;
