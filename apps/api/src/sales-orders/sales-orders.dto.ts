import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsEnum,
  IsNumber,
  IsOptional,
  IsPositive,
  IsString,
  IsUUID,
  Length,
  Max,
  Min,
  ValidateNested,
} from 'class-validator';
import { PaginationQueryDto } from '../common/pagination.js';
import { DateOnly, Trim } from '../common/validation.js';
import { OrderStatus } from '../generated/prisma/client.js';

const MAX_QTY = 99_999_999_999.999;

/** A line to sell. There is deliberately no price field: the server prices it. */
export class SaleItemDto {
  @ApiProperty() @IsUUID() productId: string;
  @ApiProperty() @IsUUID() unitId: string;

  @ApiProperty({ example: 5, description: 'In the chosen unit' })
  @IsNumber({ maxDecimalPlaces: 3, allowNaN: false, allowInfinity: false })
  @IsPositive()
  @Max(MAX_QTY)
  quantity: number;

  @ApiPropertyOptional({
    example: 2.5,
    description: 'Line discount in %. Salesmen: at most 5.',
  })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2, allowNaN: false, allowInfinity: false })
  @Min(0)
  @Max(100)
  discountPercent?: number;
}

export class CreateSalesOrderDto {
  @ApiProperty() @IsUUID() partyId: string;
  @ApiProperty() @IsUUID() godownId: string;

  @ApiProperty({ type: [SaleItemDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(200)
  @ValidateNested({ each: true })
  @Type(() => SaleItemDto)
  items: SaleItemDto[];

  @ApiPropertyOptional({ example: 'Deliver before 11am' })
  @IsOptional()
  @Trim()
  @IsString()
  @Length(1, 1000)
  notes?: string;

  @ApiPropertyOptional({
    description:
      'Unique id generated by the (offline) client. Sending the same id again returns the existing order.',
  })
  @IsOptional()
  @IsUUID()
  clientUuid?: string;

  @ApiPropertyOptional({
    description:
      'Office staff booking for a salesman. Ignored for salesmen (always themselves).',
  })
  @IsOptional()
  @IsUUID()
  salesmanId?: string;
}

export class UpdateSalesOrderDto {
  @ApiPropertyOptional() @IsOptional() @IsUUID() godownId?: string;

  @ApiPropertyOptional({
    type: [SaleItemDto],
    description: 'Replaces all items',
  })
  @IsOptional()
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(200)
  @ValidateNested({ each: true })
  @Type(() => SaleItemDto)
  items?: SaleItemDto[];

  @ApiPropertyOptional()
  @IsOptional()
  @Trim()
  @IsString()
  @Length(1, 1000)
  notes?: string;
}

export class CancelDto {
  @ApiProperty({ example: 'Party changed their mind' })
  @Trim()
  @IsString()
  @Length(3, 500)
  reason: string;
}

export class ListSalesOrdersQueryDto extends PaginationQueryDto {
  @ApiPropertyOptional({ enum: OrderStatus, enumName: 'OrderStatus' })
  @IsOptional()
  @IsEnum(OrderStatus)
  status?: OrderStatus;

  @ApiPropertyOptional() @IsOptional() @IsUUID() partyId?: string;

  @ApiPropertyOptional({
    description: 'Ignored for salesmen (always themselves)',
  })
  @IsOptional()
  @IsUUID()
  salesmanId?: string;

  @ApiPropertyOptional({ example: '2026-09-01' })
  @IsOptional()
  @DateOnly()
  from?: string;

  @ApiPropertyOptional({ example: '2026-09-30' })
  @IsOptional()
  @DateOnly()
  to?: string;
}
